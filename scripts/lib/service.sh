#!/usr/bin/env bash
# scripts/lib/service.sh - Systemd service unit generation, installation, and management
set -euo pipefail

SYSTEMD_UNIT_PATH="/etc/systemd/system/e-webui.service"

render_service_unit() {
    local app_dir="${1:-/opt/e-webui}"
    local app_port="${2:-8080}"
    local ollama_host="${3:-http://127.0.0.1:11434}"

    cat <<EOF
[Unit]
Description=e-webui Application Service
After=network.target network-online.target
Wants=network-online.target

[Service]
Type=simple
User=root
WorkingDirectory=${app_dir}/current
ExecStart=${app_dir}/current/venv/bin/uvicorn app.main:app --host 0.0.0.0 --port ${app_port}
Restart=always
RestartSec=3

# Persistent and Deployment Environment Configuration
EnvironmentFile=-${app_dir}/deployment.env
EnvironmentFile=-${app_dir}/shared/.env

# Default Fallback Environment
Environment="PYTHONPATH=${app_dir}/current"
Environment="APP_HOST=0.0.0.0"
Environment="APP_PORT=${app_port}"
Environment="OLLAMA_HOST=${ollama_host}"

# Offline Model Runtime Configuration
Environment="HF_HUB_OFFLINE=1"
Environment="TRANSFORMERS_OFFLINE=1"
Environment="HF_DATASETS_OFFLINE=1"
Environment="KOKORO_MODEL_DIR=${app_dir}/shared/models/kokoro"

# Security Hardening
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
}

install_service_unit() {
    local c_name="$1"
    local app_dir="${2:-/opt/e-webui}"
    local app_port="${3:-8080}"
    local ollama_host="${4:-http://127.0.0.1:11434}"

    local tmp_unit
    tmp_unit=$(mktemp "/tmp/e-webui-unit.XXXXXX")
    register_cleanup "rm -f '${tmp_unit}'"

    render_service_unit "${app_dir}" "${app_port}" "${ollama_host}" > "${tmp_unit}"

    # Ensure parent directory exists in container before pushing
    run_in_container "${c_name}" mkdir -p "$(dirname "${SYSTEMD_UNIT_PATH}")"

    # Push to container
    container_push "${tmp_unit}" "${c_name}${SYSTEMD_UNIT_PATH}"
    rm -f "${tmp_unit}"

    # Render and push deployment.env
    local tmp_env
    tmp_env=$(mktemp "/tmp/e-webui-env.XXXXXX")
    register_cleanup "rm -f '${tmp_env}'"
    cat <<ENV_EOF > "${tmp_env}"
# Generated by e-webui deployment lifecycle manager
APP_PORT=${app_port}
OLLAMA_HOST=${ollama_host}
KOKORO_MODEL_DIR=${app_dir}/shared/models/kokoro
HF_HUB_OFFLINE=1
TRANSFORMERS_OFFLINE=1
HF_DATASETS_OFFLINE=1
ENV_EOF
    container_push "${tmp_env}" "${c_name}${app_dir}/deployment.env"
    rm -f "${tmp_env}"

    run_in_container "${c_name}" systemctl daemon-reload
    run_in_container "${c_name}" systemctl enable e-webui
}

service_is_active() {
    local c_name="$1"
    run_in_container "${c_name}" systemctl is-active --quiet e-webui 2>/dev/null
}

restart_service() {
    local c_name="$1"
    run_in_container "${c_name}" systemctl restart e-webui
}

stop_service() {
    local c_name="$1"
    run_in_container "${c_name}" systemctl stop e-webui 2>/dev/null || true
}

remove_service() {
    local c_name="$1"
    run_in_container "${c_name}" systemctl stop e-webui 2>/dev/null || true
    run_in_container "${c_name}" systemctl disable e-webui 2>/dev/null || true
    run_in_container "${c_name}" rm -f "${SYSTEMD_UNIT_PATH}" 2>/dev/null || true
    run_in_container "${c_name}" systemctl daemon-reload 2>/dev/null || true
}
